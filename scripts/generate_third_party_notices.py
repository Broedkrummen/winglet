#!/usr/bin/env python3
"""Package complete notice text for the app and plugin; --check detects stale committed copies.

Repository text is canonical UTF-8/LF. Apart from newline canonicalization, source notice text is
embedded verbatim: copyright, license and provenance are never summarized or stripped.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = Path("app/src/generated/third-party-notices.json")
PLUGIN = Path("plugin/THIRD_PARTY_NOTICES.md")


def render(root: Path) -> dict[Path, bytes]:
    sources = sorted((root / "third_party/notices").glob("*.md"), key=lambda p: p.name)
    if not sources:
        raise ValueError("No third_party/notices/*.md sources found; refusing to erase packaged notices")
    notices = []
    parts = ["# Third-party notices\n\nGenerated by scripts/generate_third_party_notices.py. "
             "The complete source notices below accompany the distributed Winglet plugin.\n"]
    for path in sources:
        text = path.read_text(encoding="utf-8")
        if not text.strip():
            raise ValueError(f"Empty notice: {path.name}")
        heading = next((line[2:].strip() for line in text.splitlines() if line.startswith("# ")), path.stem)
        notices.append({"file": path.name, "title": heading, "text": text})
        parts.append(f"\n---\n\nSource: third_party/notices/{path.name}\n\n" + text)
        if not text.endswith("\n"):
            parts.append("\n")
    return {APP: (json.dumps(notices, ensure_ascii=False, indent=2) + "\n").encode("utf-8"),
            PLUGIN: "".join(parts).encode("utf-8")}


def main(argv=None, *, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail without writing if either packaged copy is stale")
    args = parser.parse_args(argv)
    try:
        outputs = render(root)
    except (OSError, UnicodeError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    stale = [path for path, content in outputs.items()
             if not (root / path).is_file() or (root / path).read_bytes() != content]
    if args.check:
        for path in stale:
            print(f"Stale packaged notice: {path}", file=sys.stderr)
        if stale:
            print("Run python scripts/generate_third_party_notices.py", file=sys.stderr)
        return int(bool(stale))
    for path in stale:
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_bytes(outputs[path])
        temporary.replace(target)
        print(f"Generated {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
